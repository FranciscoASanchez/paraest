	SUBROUTINE ASSocISOFmezclasSUB(NC,DC,TEMPCRIT,NG,NU,QAREA,TSTR,
     @GSTR,GDOT,GDDOT,RKIJ,RKTIJ,ALFAIJ,NGA,ONUASOC,
     @MASSOC,ENASS,RKASS,
     @TEMP,PRESS,X1,Y1,APART1,APART2,ZLL,ZVV,IERRMIXISOF)
C ------------------------------------------------------------------
C ------------------------------------------------------------------
C
C TEMP  = TEMPERATURA DEL FLASH , KELVIN
C PRESS = PRESION DEL FLASH, ATM
C ZLL= FACTOR DE COMPRESIBILIDAD (CALCULADO) FASE LIQUIDA
C ZVV= FACTOR DE COMPRESIBILIDAD (CALCULADO) FASE VAPOR
C
C Calcula 
C                                |    |
C    Ø (T,P,X)exp  * X           |    |    Ø (T,P,X)exp  * X       
C        1 liq           1exp       |    |        2 liq           2exp  
C    ----------------------  - 1.|  Y    |    ----------------------   -   1.
C    Ø (T,P,Y)exp  * Y           |    |    Ø (T,P,Y)exp  * Y       
C        1 vap           1exp       |    |        2 vap           2exp  
C                                |    |
C
C Es decir que calcula el apartamiento de la isofugacidad para cada 
C      componente, para un dado dato 
C  experimental de VLE (flash binario) y para un conjunto dado de parametros 
C   de la ASSOC-GC-EOS
C
C
	IMPLICIT REAL*8 (A-H,O-Z)
C
	DIMENSION DC(2) 
	DIMENSION  TEMPCRIT(2)
C
C DIMENSIONAMIENTO DE ARREGLOS RELACIONADOS CON EL CARACTER GRUPAL
C DEL TERMINO DE DISPERSION
C
	DIMENSION NU(10,2), QAREA(10), TSTR(10), GSTR(10) 
	DIMENSION GDOT(10), GDDOT(10), RKIJ(10,10), RKTIJ(10,10)
	DIMENSION ALFAIJ(10,10) 
C
C DIMENSIONAMIENTO DE ARREGLOS RELACIONADOS CON EL TERMINO DE ASOCIACION
C
        DIMENSION MASSOC(12),ENASS(6,12,6,12), RKASS(6,12,6,12)
        DIMENSION ONUASOC(12,2)
C
C
C DIMENSIONAMIENTO DE ARREGLOS PROPIOS DE UN FLASH
C
	DIMENSION XLIQ(2), YVAP(2)
C
C DIMENSIONAMIENTO DE COEFICIENTES DE FUGACIDAD EN FASE LIQUIDA (LQ) Y 
C VAPOR (VP)
C
	DIMENSION FFILQ(2) 
	DIMENSION FFIVP(2) 
C
	IERRMIXISOF= 0
	aux=0.
C
	CALL ISOFTR(X1,Y1,YVAP,XLIQ)
C
	RUNIV = 82.05 !ATM cm3 / (K mol)
C
C
C INICIALIZACION DEL VOLUMEN LIQUIDO
C
 	CALL LIQMIXINICI(NC,DC,TEMPCRIT,NG,NU,QAREA,TSTR,
     @GSTR,GDOT,GDDOT,RKIJ,RKTIJ,ALFAIJ,NGA,ONUASOC,
     @MASSOC,ENASS,RKASS,TEMP,PRESS,XLIQ,VLIQ,IERRINI)
C
C  SI HAY ERROR FIN DE EJECUCION
C
	IF(IERRINI.NE.0) WRITE(6,*) 'ERROR LIQ INI'
	IF(IERRINI.NE.0) GO TO 107
C
C COMPATIBILIZACION DEL VOLUMEN DEL LIQUIDO CON LA PRESION PRESS
C
	CALL LIQMIXCOMPAT(NC,DC,TEMPCRIT,NG,NU,QAREA,TSTR,
     @GSTR,GDOT,GDDOT,RKIJ,RKTIJ,ALFAIJ,NGA,ONUASOC,
     @MASSOC,ENASS,RKASS,TEMP,PRESS,XLIQ,VLIQ,FFILQ,IERRLC)
C
C  SI HAY ERROR FIN DE EJECUCION
C
	IF(IERRLC.NE.0) WRITE(6,*) 'ERROR LIQ COMPAT'
	IF(IERRLC.NE.0) GO TO 107
C
C INICIALIZACION DEL VOLUMEN DEL VAPOR
C
	 If (aux==0) then
 	CALL VAPMIXINICI(NC,DC,TEMPCRIT,NG,NU,QAREA,TSTR,
     @GSTR,GDOT,GDDOT,RKIJ,RKTIJ,ALFAIJ,NGA,ONUASOC,
     @MASSOC,ENASS,RKASS,TEMP,PRESS,YVAP,VVAP,IERRVI)
C
C  SI HAY ERROR FIN DE EJECUCION
C
!	IF(IERRVI.NE.0) WRITE(6,*) 'ERROR VAPINI'
	!IF(IERRVI.NE.0) GO TO 107
C
C COMPATIBILIZACION DEL VOLUMEN DEL VAPOR CON LA PRESION PRESS
C
	CALL VAPMIXCOMPAT(NC,DC,TEMPCRIT,NG,NU,QAREA,TSTR,
     @GSTR,GDOT,GDDOT,RKIJ,RKTIJ,ALFAIJ,NGA,ONUASOC,
     @MASSOC,ENASS,RKASS,TEMP,PRESS,YVAP,VVAP,FFIVP,IERRVC)
C
C  SI HAY ERROR FIN DE EJECUCION
C
	!IF(IERRVC.NE.0) WRITE(6,*) 'ERROR VAP COMPAT'
	!IF(IERRVC.NE.0) GO TO 107
	If (ierrvc.ne.0.or.ierrvi.ne.0) aux=1

	end if
C
C CALCULO DE FACTORES DE COMPRESIBILIDAD
C
	If(aux==1)then

	 	CALL LIQMIXINICI(NC,DC,TEMPCRIT,NG,NU,QAREA,TSTR,
     @GSTR,GDOT,GDDOT,RKIJ,RKTIJ,ALFAIJ,NGA,ONUASOC,
     @MASSOC,ENASS,RKASS,TEMP,PRESS,yvap,vvap,IERRINI)
C
C  SI HAY ERROR FIN DE EJECUCION
C
		IF(IERRINI.NE.0) WRITE(6,*) 'ERROR LIQ INI'
		IF(IERRINI.NE.0) GO TO 107
C
C COMPATIBILIZACION DEL VOLUMEN DEL LIQUIDO CON LA PRESION PRESS
C
	CALL LIQMIXCOMPAT(NC,DC,TEMPCRIT,NG,NU,QAREA,TSTR,
     @GSTR,GDOT,GDDOT,RKIJ,RKTIJ,ALFAIJ,NGA,ONUASOC,
     @MASSOC,ENASS,RKASS,TEMP,PRESS,yvap,vvap,ffivp,IERRLC)
C
C  SI HAY ERROR FIN DE EJECUCION
C
	IF(IERRLC.NE.0) WRITE(6,*) 'ERROR LIQ COMPAT'
	IF(IERRLC.NE.0) GO TO 107


	end if


	ZLL= PRESS*VLIQ/RUNIV/TEMP
	ZVV= PRESS*VVAP/RUNIV/TEMP
C
C
C CALCULO DEL APARTAMIENTO DE LA "ISOFUGACIDAD" PARA AMBOS COMPONENTES
C
	APART1 = FFILQ(1)*XLIQ(1) / (FFIVP(1)*YVAP(1))  -  1.
	APART2 = FFILQ(2)*XLIQ(2) / (FFIVP(2)*YVAP(2))  -  1.
C
C	WRITE(6,*) 'AP1%          AP2%'
C	WRITE(6,*) (APART1*100.),(APART2*100)
C
C	CALL LIB$SHOW_TIMER(,2,,)
C
 107	IF(IERRINI.NE.0.OR.IERRLC.NE.0)  THEN
				IERRMIXISOF= 1
	 ELSE
				IERRMIXISOF= 0
	END IF
C
	!write (1,*) "TEMP=", TEMP 
     	!write (1,*)	"PRESS=", PRESS
      !write (1,*) "FFILQ(1)=", FFILQ(1)
 	

	!write (1,*) "FFIVP(1)=", FFIVP(1)
	!write (1,*) "FFILQ(2)=", FFILQ(2)
	!write (1,*) "FFIVP(2)=", FFIVP(2)
	
 	END !FIN ASSocISOFmezclasSUB  
C///////////////////////////////////////////
	SUBROUTINE ISOFTR(X1,Y1,YVAP,XLIQ)
	IMPLICIT REAL*8 (A-H,O-Z)
	DIMENSION XLIQ(2), YVAP(2)
C
C X1 = FRACCION MOLAR DEL COMPONENTE 1 EN FASE LIQUIDA
C Y1 = FRACCION MOLAR DEL COMPONENTE 1 EN FASE VAPOR
C
C
	YVAP(1) =  Y1
	YVAP(2) = 1 - Y1
C
	XLIQ(1) = X1
	XLIQ(2) = 1 - X1	
C
	END !FIN ISOFTR
