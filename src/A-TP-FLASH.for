	SUBROUTINE UPDATE5(RESFI1L,RESFI1V,RESFI2L,
     @RESFI2V,RESERVY1,RESERVX1,YVAP,XLIQ)
	IMPLICIT REAL*8 (A-H,O-Z)
	DIMENSION XLIQ(2), YVAP(2)
C
C ENCUENTRA NUEVOS VALORES DE XLIQ E YVAP POR SUSTITUCION DIRECTA
C  (CON LA ECUACION DE ISOFUGACIDAD)
C
C
c	write(6,*)"RESFI1L=" ,RESFI1L 

	XLIQ(1) = RESERVY1 * RESFI1V / RESFI1L 
C
	YVAP(2) = (1 - RESERVX1) * RESFI2L / RESFI2V 

C		
 	XLIQ(2) = 1 - XLIQ(1)
C
	YVAP(1) = 1 - YVAP(2)
C
	END !FIN UPDATE5
