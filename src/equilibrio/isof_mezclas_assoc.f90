      SUBROUTINE ASSocISOFmezclasSUB(NC,DC,TEMPCRIT,NG,NU,QAREA,TSTR,&
     &GSTR,GDOT,GDDOT,RKIJ,RKTIJ,ALFAIJ,NGA,ONUASOC,&
     &MASSOC,ENASS,RKASS,&
     &TEMP,PRESS,X1,Y1,APART1,APART2,ZLL,ZVV,IERRMIXISOF)
! ------------------------------------------------------------------
! ------------------------------------------------------------------
!
! TEMP  = TEMPERATURA DEL FLASH , KELVIN
! PRESS = PRESION DEL FLASH, ATM
! ZLL= FACTOR DE COMPRESIBILIDAD (CALCULADO) FASE LIQUIDA
! ZVV= FACTOR DE COMPRESIBILIDAD (CALCULADO) FASE VAPOR
!
! Calcula
!                                |    |
!    Ø (T,P,X)exp  * X           |    |    Ø (T,P,X)exp  * X
!        1 liq           1exp       |    |        2 liq           2exp
!    ----------------------  - 1.|  Y    |    ----------------------   -   1.
!    Ø (T,P,Y)exp  * Y           |    |    Ø (T,P,Y)exp  * Y
!        1 vap           1exp       |    |        2 vap           2exp
!                                |    |
!
! Es decir que calcula el apartamiento de la isofugacidad para cada
!      componente, para un dado dato
!  experimental de VLE (flash binario) y para un conjunto dado de parametros
!   de la ASSOC-GC-EOS
!
!
      IMPLICIT REAL*8 (A-H,O-Z)
      integer, parameter :: NGM = 20
!
      DIMENSION DC(3), TEMPCRIT(3)
!
! DIMENSIONAMIENTO DE ARREGLOS RELACIONADOS CON EL CARACTER GRUPAL
! DEL TERMINO DE DISPERSION
!
      DIMENSION NU(NGM,3), QAREA(NGM), TSTR(NGM), GSTR(NGM)
      DIMENSION GDOT(NGM), GDDOT(NGM), RKIJ(NGM,NGM), RKTIJ(NGM,NGM)
      DIMENSION ALFAIJ(NGM,NGM)
!
! DIMENSIONAMIENTO DE ARREGLOS RELACIONADOS CON EL TERMINO DE ASOCIACION
!
        DIMENSION MASSOC(12),ENASS(6,12,6,12), RKASS(6,12,6,12)
        DIMENSION ONUASOC(12,3)
!
!
! DIMENSIONAMIENTO DE ARREGLOS PROPIOS DE UN FLASH
!
      DIMENSION XLIQ(3), YVAP(3)
!
! DIMENSIONAMIENTO DE COEFICIENTES DE FUGACIDAD EN FASE LIQUIDA (LQ) Y
! VAPOR (VP)
!
      DIMENSION FFILQ(3)
      DIMENSION FFIVP(3)
!
      IERRMIXISOF= 0
      aux=0.
!
      CALL ISOFTR(X1,Y1,YVAP,XLIQ)
!
      RUNIV = 82.05 !ATM cm3 / (K mol)
!
!
! INICIALIZACION DEL VOLUMEN LIQUIDO
!
      CALL LIQMIXINICI(NC,DC,TEMPCRIT,NG,NU,QAREA,TSTR,&
     &GSTR,GDOT,GDDOT,RKIJ,RKTIJ,ALFAIJ,NGA,ONUASOC,&
     &MASSOC,ENASS,RKASS,TEMP,PRESS,XLIQ,VLIQ,IERRINI)
!
!  SI HAY ERROR FIN DE EJECUCION
!
      IF(IERRINI.NE.0) WRITE(6,*) 'ERROR LIQ INI'
      IF(IERRINI.NE.0) GO TO 107
!
! COMPATIBILIZACION DEL VOLUMEN DEL LIQUIDO CON LA PRESION PRESS
!
      CALL LIQMIXCOMPAT(NC,DC,TEMPCRIT,NG,NU,QAREA,TSTR,&
     &GSTR,GDOT,GDDOT,RKIJ,RKTIJ,ALFAIJ,NGA,ONUASOC,&
     &MASSOC,ENASS,RKASS,TEMP,PRESS,XLIQ,VLIQ,FFILQ,IERRLC)
!
!  SI HAY ERROR FIN DE EJECUCION
!
      IF(IERRLC.NE.0) WRITE(6,*) 'ERROR LIQ COMPAT'
      IF(IERRLC.NE.0) GO TO 107
!
! INICIALIZACION DEL VOLUMEN DEL VAPOR
!
       If (aux==0) then
      CALL VAPMIXINICI(NC,DC,TEMPCRIT,NG,NU,QAREA,TSTR,&
     &GSTR,GDOT,GDDOT,RKIJ,RKTIJ,ALFAIJ,NGA,ONUASOC,&
     &MASSOC,ENASS,RKASS,TEMP,PRESS,YVAP,VVAP,IERRVI)
!
!  SI HAY ERROR FIN DE EJECUCION
!
!	IF(IERRVI.NE.0) WRITE(6,*) 'ERROR VAPINI'
	!IF(IERRVI.NE.0) GO TO 107
!
! COMPATIBILIZACION DEL VOLUMEN DEL VAPOR CON LA PRESION PRESS
!
      CALL VAPMIXCOMPAT(NC,DC,TEMPCRIT,NG,NU,QAREA,TSTR,&
     &GSTR,GDOT,GDDOT,RKIJ,RKTIJ,ALFAIJ,NGA,ONUASOC,&
     &MASSOC,ENASS,RKASS,TEMP,PRESS,YVAP,VVAP,FFIVP,IERRVC)
!
!  SI HAY ERROR FIN DE EJECUCION
!
	!IF(IERRVC.NE.0) WRITE(6,*) 'ERROR VAP COMPAT'
	!IF(IERRVC.NE.0) GO TO 107
      If (ierrvc.ne.0.or.ierrvi.ne.0) aux=1

      end if
!
! CALCULO DE FACTORES DE COMPRESIBILIDAD
!
      If(aux==1)then

       	CALL LIQMIXINICI(NC,DC,TEMPCRIT,NG,NU,QAREA,TSTR,&
     &GSTR,GDOT,GDDOT,RKIJ,RKTIJ,ALFAIJ,NGA,ONUASOC,&
     &MASSOC,ENASS,RKASS,TEMP,PRESS,yvap,vvap,IERRINI)
!
!  SI HAY ERROR FIN DE EJECUCION
!
      	IF(IERRINI.NE.0) WRITE(6,*) 'ERROR LIQ INI'
      	IF(IERRINI.NE.0) GO TO 107
!
! COMPATIBILIZACION DEL VOLUMEN DEL LIQUIDO CON LA PRESION PRESS
!
      CALL LIQMIXCOMPAT(NC,DC,TEMPCRIT,NG,NU,QAREA,TSTR,&
     &GSTR,GDOT,GDDOT,RKIJ,RKTIJ,ALFAIJ,NGA,ONUASOC,&
     &MASSOC,ENASS,RKASS,TEMP,PRESS,yvap,vvap,ffivp,IERRLC)
!
!  SI HAY ERROR FIN DE EJECUCION
!
      IF(IERRLC.NE.0) WRITE(6,*) 'ERROR LIQ COMPAT'
      IF(IERRLC.NE.0) GO TO 107


      end if


      ZLL= PRESS*VLIQ/RUNIV/TEMP
      ZVV= PRESS*VVAP/RUNIV/TEMP
!
!
! CALCULO DEL APARTAMIENTO DE LA "ISOFUGACIDAD" PARA AMBOS COMPONENTES
!
      APART1 = FFILQ(1)*XLIQ(1) / (FFIVP(1)*YVAP(1))  -  1.
      APART2 = FFILQ(2)*XLIQ(2) / (FFIVP(2)*YVAP(2))  -  1.
!
!	WRITE(6,*) 'AP1%          AP2%'
!	WRITE(6,*) (APART1*100.),(APART2*100)
!
!	CALL LIB$SHOW_TIMER(,2,,)
!
107   IF(IERRINI.NE.0.OR.IERRLC.NE.0)  THEN
      			IERRMIXISOF= 1
       ELSE
      			IERRMIXISOF= 0
      END IF
!
	!write (1,*) "TEMP=", TEMP
     	!write (1,*)	"PRESS=", PRESS
      !write (1,*) "FFILQ(1)=", FFILQ(1)


	!write (1,*) "FFIVP(1)=", FFIVP(1)
	!write (1,*) "FFILQ(2)=", FFILQ(2)
	!write (1,*) "FFIVP(2)=", FFIVP(2)

      END !FIN ASSocISOFmezclasSUB
!///////////////////////////////////////////
      SUBROUTINE ISOFTR(X1,Y1,YVAP,XLIQ)
      IMPLICIT REAL*8 (A-H,O-Z)
      DIMENSION XLIQ(2), YVAP(2)
!
! X1 = FRACCION MOLAR DEL COMPONENTE 1 EN FASE LIQUIDA
! Y1 = FRACCION MOLAR DEL COMPONENTE 1 EN FASE VAPOR
!
!
      YVAP(1) =  Y1
      YVAP(2) = 1 - Y1
!
      XLIQ(1) = X1
      XLIQ(2) = 1 - X1
!
      END !FIN ISOFTR
