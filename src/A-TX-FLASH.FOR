	SUBROUTINE UPDATE(XISOF,FISOF,YVAP,PRESS)
	IMPLICIT REAL*8 (A-H,O-Z)
	DIMENSION FISOF(6) 
	DIMENSION XISOF(6)
	DIMENSION XLIQ(2), YVAP(2)
	DIMENSION RJAC(2,2)
C
C RECALCULA YVAP Y LA PRESION UTILIZANDO EL METODO DE NEWTON
C
C RJAC ES EL JACOBIANO (DERIVADAS PARCIALES)
C
	RJAC(1,1) = (FISOF(3)-FISOF(1))/ (XISOF(3)-XISOF(1))
C
	RJAC(1,2) = (FISOF(5)-FISOF(1))/ (XISOF(6)-XISOF(2))
C
	RJAC(2,1) = (FISOF(4)-FISOF(2))/ (XISOF(3)-XISOF(1))
C
	RJAC(2,2) = (FISOF(6)-FISOF(2))/ (XISOF(6)-XISOF(2))
C
C CALCULO DEL DETERMINANTE
C
	DETERM = RJAC(1,1)*RJAC(2,2) - RJAC(1,2)*RJAC(2,1)
C
C RECALCULO E Y1 y PRESION
C
	YVAPAUX = FISOF(2) * RJAC(1,2) - FISOF(1) * RJAC(2,2)
	YVAP(1) = YVAPAUX/DETERM + YVAP(1) 
	YVAP(2) = 1 - YVAP(1)
C
	PRESSAUX   = FISOF(1) * RJAC(2,1) - FISOF(2) * RJAC(1,1)
	PRESS   =  PRESSAUX/DETERM + PRESS
C	
	END !FIN  UPDATE
C//////////////////////////////////////////////////////////////////////
C//////////////////////////////////////////////////////////////////////
	SUBROUTINE UPDATE9(RESFI1L,RESFI1V,RESFI2L,
     @RESFI2V,RESERVY1,RESERVPRESS,XLIQ,YVAP,PRESS)
	IMPLICIT REAL*8 (A-H,O-Z)
	DIMENSION XLIQ(2), YVAP(2)
C
C ENCUENTRA NUEVOS VALORES DE PRESS E YVAP POR SUSTITUCION DIRECTA
C  (CON LA ECUACION DE ISOFUGACIDAD)
C
	AUX1 = RESFI2L * XLIQ(2) / (RESFI2V * (1-RESERVY1)) 
	PRESS = RESERVPRESS * AUX1
C
	YVAP(1) = RESFI1L * XLIQ(1) / RESFI1V
C
	YVAP(2) = 1 - YVAP(1)
C
C
	END !FIN UPDATE9
