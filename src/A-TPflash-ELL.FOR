	SUBROUTINE TPflashELL(NC,DC,TEMPCRIT,NG,NU,QAREA,TSTR,
     @GSTR,GDOT,GDDOT,RKIJ,RKTIJ,ALFAIJ,NGA,ONUASOC,
     @MASSOC,ENASS,RKASS,TEMP,
     @PRESS,X1,Y1,ZLIQUIDO,ZVAPOR,IERRTP)   
C
C
C CALCULA UN FLASH A T y P PARA UN SISTEMA BINARIO
C    CON EL MODELO ASS-GC-EOS
C
C UTILIZA METODO DE NEWTON. SI ESTE DIVERGE APLICA SUSTITUCION DIRECTA
C
C
	IMPLICIT REAL*8 (A-H,O-Z)
C
	DIMENSION DC(2) 
	DIMENSION  TEMPCRIT(2)
C
C DIMENSIONAMIENTO DE ARREGLOS RELACIONADOS CON EL CARACTER GRUPAL
C DEL TERMINO DE DISPERSION
C
	DIMENSION NU(10,2), QAREA(10), TSTR(10), GSTR(10) 
	DIMENSION GDOT(10), GDDOT(10), RKIJ(10,10), RKTIJ(10,10)
	DIMENSION ALFAIJ(10,10) 
C
C DIMENSIONAMIENTO DE ARREGLOS RELACIONADOS CON EL TERMINO DE ASOCIACION
C
        DIMENSION MASSOC(12),ENASS(6,12,6,12), RKASS(6,12,6,12)
        DIMENSION ONUASOC(12,2)
C
C
C DIMENSIONAMIENTO DE ARREGLOS PROPIOS DE UN CALCULO FLASH
C
	DIMENSION XLIQ(2), YVAP(2)
C
C DIMENSIONAMIENTO DE COEFICIENTES DE FUGACIDAD EN FASE LIQUIDA (LQ) Y 
C VAPOR (VP)
C
	DIMENSION FFILQ(2) 
	DIMENSION FFIVP(2) 
C
C VALORES DE X Y DE LA FUNCION QUE DEBE HACERSE NULA
C
	DIMENSION FISOFC(2)
	DIMENSION FISOF(6) 
	DIMENSION XISOF(6)
C
C FISOF(1)  = DIFERENCIA ENTRE LAS FUGACIDADES DEL COMP 1 EN LIQ Y VAPOR
C		(si converge esto termina siendo cero), EN EL PUNTO INICIAL 
C                                                         (O CENTRAL)
C FISOF(2)  = IDEM FISOF(1) pero para el componente 2
C FISOF(3)  = IDEM FISOF(1) pero cuando se perturba Y1
C FISOF(4)  = IDEM FISOF(2) pero cuando se perturba Y1
C FISOF(5)  = IDEM FISOF(1) pero cuando se perturba X1
C FISOF(6)  = IDEM FISOF(2) pero cuando se perturba X1
C
C XISOF(1)  = Y1 inicial (o central), fraccion molar del componente 1 en 
C	      fase vapor
C
C XISOF(2)  = X1 inicial (o central), fraccion molar del componente 1 en 
C   	      FASE LIQUIDA 
C
C
C
C
C
C
C LECTURA DE TEMPERATURA,PRESION  Y DE LOS VALORES INCIALES DE LA
C    COMPOSICION DEL VAPOR Y DE LIQUIDO
C
C
	ITERRR=0

	IERRTP = 0
	RUNIV = 82.05 !ATM cm3 / (K mol)
C
	XLIQ(1)= X1
	XLIQ(2)= 1. - X1
	YVAP(1)= Y1
	YVAP(2)= 1. - Y1
C
C VARIABLE AUXILIAR
C
 909	NINJA = 1

 	ITERRR=ITERRR+1

C
C ALMACENO LOS VALORES CENTRALES DE Y1 y X1
C
 	RESERVY1 = YVAP(1)
	RESERVX1 = XLIQ(1)
C
C
C INICIALIZACION DEL VOLUMEN LIQUIDO
C

 192	CALL LIQMIXINICI(NC,DC,TEMPCRIT,NG,NU,QAREA,TSTR,
     @GSTR,GDOT,GDDOT,RKIJ,RKTIJ,ALFAIJ,NGA,ONUASOC,
     @MASSOC,ENASS,RKASS,TEMP,PRESS,XLIQ,VLIQ,IERRINI)
!		write (2,*) "VLIQdepoisdeliqmixini=", VLIQ
	

C
C  SI HAY ERROR FIN DE EJECUCION
C
	IF(IERRINI.NE.0) WRITE(6,*) 'ERROR LIQ INI'
	IF(IERRINI.NE.0) GO TO 107
C
C COMPATIBILIZACION DEL VOLUMEN DEL LIQUIDO CON LA PRESION PRESS
C
!	write (2,*) "VLIQantesdeliqmixcompat=", VLIQ
	CALL LIQMIXCOMPAT(NC,DC,TEMPCRIT,NG,NU,QAREA,TSTR,
     @GSTR,GDOT,GDDOT,RKIJ,RKTIJ,ALFAIJ,NGA,ONUASOC,
     @MASSOC,ENASS,RKASS,TEMP,PRESS,XLIQ,VLIQ,FFILQ,IERRLC)
C
C  SI HAY ERROR FIN DE EJECUCION

	IF(IERRLC.NE.0) WRITE(6,*) 'ERROR LIQ COMPAT'
	IF(IERRLC.NE.0) GO TO 107
C
C ALMACENO VOLUMEN LIQUIDO CORRESPONDIENTE AL PUNTO CENTRAL
C
	IF(NINJA.EQ.1) RESERVVLIQ = VLIQ
C
C INICIALIZACION DEL VOLUMEN DEL VAPOR
C
 888	CALL LIQMIXINICI(NC,DC,TEMPCRIT,NG,NU,QAREA,TSTR,
     @GSTR,GDOT,GDDOT,RKIJ,RKTIJ,ALFAIJ,NGA,ONUASOC,
     @MASSOC,ENASS,RKASS,TEMP,PRESS,YVAP,VVAP,IERRVI)


	!write(6,*) "vvap", vvap
C 
C  SI HAY ERROR FIN DE EJECUCION
C
	IF(IERRVI.NE.0) WRITE(6,*) 'ERROR VAPINI'
	IF(IERRVI.NE.0) GO TO 107
C
C COMPATIBILIZACION DEL VOLUMEN DEL VAPOR CON LA PRESION PRESS
C
	CALL LIQMIXCOMPAT(NC,DC,TEMPCRIT,NG,NU,QAREA,TSTR,
     @GSTR,GDOT,GDDOT,RKIJ,RKTIJ,ALFAIJ,NGA,ONUASOC,
     @MASSOC,ENASS,RKASS,TEMP,PRESS,YVAP,VVAP,FFIVP,IERRVC)
	!write(6,*) "vvap", vvap

C
C  SI HAY ERROR FIN DE EJECUCION
C
		IF(IERRVC.NE.0) WRITE(6,*) 'ERROR VAP COMPAT'
		IF(IERRVC.NE.0) GO TO 107
C
C ALMACENO VOLUMEN VAPOR CORRESPONDIENTE AL PUNTO CENTRAL
C
	IF(NINJA.EQ.1) RESERVVVAP = VVAP
C
C
C CALCULO DE LA "ISOFUGACIDAD"
C
	FISOFC(1)= FFILQ(1)*XLIQ(1) - FFIVP(1)*YVAP(1)
	FISOFC(2)= FFILQ(2)*XLIQ(2) - FFIVP(2)*YVAP(2)
C
C ALMACENO COEFICIENTES DE FUGACIDAD CORRESPONDIENTES AL PTO. CENTRAL
C
	IF(NINJA.EQ.1) THEN
		RESFI1L = FFILQ(1)
		RESFI1V = FFIVP(1)
		RESFI2L = FFILQ(2)
		RESFI2V = FFIVP(2)
	 ELSE
	  CONTINUE
	END IF
C
C ALMACENAMIENTO DE VALORES
C
	XISOF(2*NINJA-1) = YVAP(1)
	XISOF(2*NINJA) = XLIQ(1)
C
	FISOF(2*NINJA-1) = FISOFC(1)
	FISOF(2*NINJA)   = FISOFC(2)
C
C PERTURBO YVAP(1)
C
	IF(NINJA.EQ.1) THEN
				YVAP(1) = YVAP(1)*(1.001)
		                IF(YVAP(1).GT.1.) YVAP(1) = 2.-YVAP(1)
				YVAP(2) = 1 - YVAP(1)
				XLIQ(1) = RESERVX1
				XLIQ(2) = 1 - XLIQ(1)
				NINJA = 2
c		WRITE(6,*)"XLIQ2=", XLIQ
				GO TO 888
		       ELSE
				CONTINUE
	END IF
C
C PERTURBO XLIQ(1)			
C
	IF(NINJA.EQ.2)  THEN
				XLIQ(1) = XLIQ(1)*(1.001)
				IF(XLIQ(1).GT.1.) XLIQ(1)= 2.-XLIQ(1)
				XLIQ(2) = 1 - XLIQ(1)
				YVAP(1) = RESERVY1
				YVAP(2) = 1 - YVAP(1)
				NINJA = 3

				GO TO 192
			ELSE
				CONTINUE
	END IF		   
C
C ACTUALIZACION DE Y1 y X1  aplicando met. de Newton (o sust. directa)
C
	IF(NINJA.EQ.3) THEN 
C
				XLIQ(1) = RESERVX1
				XLIQ(2) = 1 - XLIQ(1)
				YVAP(1) = RESERVY1
				YVAP(2) = 1 - YVAP(1)
				CALL UPDATE2(XISOF,FISOF,YVAP,XLIQ)

C
C        			Si Newton no funciona ==> Sustitucion 
C				directa
C
				IF(XLIQ(1).LT.0.OR.XLIQ(1).GT.1.OR.
     @                          YVAP(1).LT.0.OR.YVAP(1).GT.1) THEN
C
				 CALL UPDATE5(RESFI1L,RESFI1V,RESFI2L,
     @RESFI2V,RESERVY1,RESERVX1,YVAP,XLIQ)
				 ELSE
				  CONTINUE
				END IF
C		
C				TEST DE CONVERGENCIA
C

	IF (ITERRR.GT.20) THEN
		IERRTP = 1
		GOTO 107
	END IF

				IF(DABS(YVAP(1)-RESERVY1).LT.1.D-4.AND
     @.DABS(XLIQ(1)-RESERVX1).LT.1.D-4) GO TO 191
C
				GO TO 909
		       ELSE
				CONTINUE
	END IF   
C
C SI SE CUMPLE EL TEST DE CONVERGENCIA EL PROGRAMA INFORMA TODO LO 
C  REFERENTE AL PUNTO CENTRAL
C
 191   	XLIQ(1) = RESERVX1
	XLIQ(2) = 1 - XLIQ(1)
	YVAP(1) = RESERVY1
	YVAP(2) = 1 - YVAP(1)
	VLIQ = RESERVVLIQ
	VVAP = RESERVVVAP
	ZLIQUIDO = PRESS*VLIQ/RUNIV/TEMP 
	ZVAPOR   = PRESS*VVAP/RUNIV/TEMP  
	X1 = XLIQ(1)
	Y1 = YVAP(1)
C
C LAS VARIABLES DE INTERES ESTAN EN , YVAP, PRESS, VLIQ Y VVAP, AL FINAL 
C DE LA CORRIDA
C
C	CALL LIB$SHOW_TIMER(,2,,)
 107	IF(IERRVI.NE.0.OR.IERRLC.NE.0.OR.
     @IERRINI.NE.0.OR.IERRVC.NE.0) IERRTP = 1
	END !FIN  ASSocTPflashSUB
