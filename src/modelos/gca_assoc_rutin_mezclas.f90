      IF(IERRFUG/=0 .OR. IERRZSIS/=0 .OR. IERRREP/=0 .OR. ierrassoc==1)  IERRINI=1
      IF(IERRFUG/=0 .OR. IERRZSIS/=0 .OR. IERRREP/=0 .OR. ierrassoc==1)  GO TO 987
