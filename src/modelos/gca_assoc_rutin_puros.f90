      SUBROUTINE LAMBDA2(NC,RN,D,RLAMBDA1,RLAMBDA2,RLAMBDA3)
      Implicit real*8 (A-H, O-Z)
      DIMENSION D(1),RN(1)
!
! CALCULO DE LOS LAMBDA NECESARIOS PARA LA CONTRIBUCION REPULSIVA
!
!
!  RLAMBDA3 ES PROPORCIONAL AL VOLUMEN OCUPADO POR LAS ESFERAS PROPIAMENTE
!   DICHAS, EXCLUYENDO EL ESPACIO INTERSTICIAL
!
      RLAMBDA1=0
      RLAMBDA2=0
      RLAMBDA3=0
!
      DO I=1,NC
        RLAMBDA1= RN(I)*D(I)     +  RLAMBDA1
        RLAMBDA2= RN(I)*D(I)**2  +  RLAMBDA2
        RLAMBDA3= RN(I)*D(I)**3  +  RLAMBDA3
      END DO
!
      ENDSUBROUTINE LAMBDA2
