	SUBROUTINE LAMBDAN(NC,RN,D,RLAMBDAN3)
	Implicit real*8 (A-H, O-Z)
	DIMENSION D(3),RN(3)

C
C CALCULO DE LOS LAMBDA3 
C
C
C  RLAMBDA3 ES PROPORCIONAL AL VOLUMEN OCUPADO POR LAS ESFERAS PROPIAMENTE
C   DICHAS, EXCLUYENDO EL ESPACIO INTERSTICIAL
C
	RLAMBDAN3=0.
C
       DO I=1,NC
		RLAMBDAN3= RN(I)*D(I)**3  +  RLAMBDAN3
	END DO
C     
	END
