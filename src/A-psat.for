	SUBROUTINE PVAP(NC,DC,RN,TEMPCRIT,TEMP,NG,NU,QAREA 
     @,TSTR,GSTR,GDOT,GDDOT,RKIJ,RKTIJ,ALFAIJ,NGA,ONUASOC,MASSOC
     @,ENASS,RKASS,RLAMBDA3,PSAT,VLIQ,VVAP,ZFASL,ZFASV,FFIFV,FFIFL,
     @IERRPVAP)
C
C PSAT = PRESION DE VAPOR, EN ATM
C ZFASL = FACTOR DE COMPRESIBILIDAD FASE LIQUIDA
C ZFASV = FACTOR DE COMPRESIBILIDAD FASE VAPOR
C FFIFV(1) = COEF DE FUGACIDAD EN EL VAPOR
C FFIFL(1) = COEF DE FUGACIDAD EN EL LIQUIDO
C
	IMPLICIT REAL*8 (A-H,O-Z)
	DIMENSION EQUIS(5) !contiene Z, phi y p_sat
C
	DIMENSION DC(1), RN(1)
	DIMENSION TEMPCRIT(1)
	DIMENSION NU(10,1), QAREA(10), TSTR(10), GSTR(10) 
	DIMENSION GDOT(10), GDDOT(10), RKIJ(10,10), RKTIJ(10,10)
	DIMENSION ALFAIJ(10,10) 
      DIMENSION MASSOC(12),ENASS(6,12,6,12), RKASS(6,12,6,12)
       DIMENSION ONUASOC(12,1)
C
	DIMENSION FFIFV(1), FFIFL(1)
C
C
C
C
C
C    VVAP = VOLUMEN DEL VAPOR EN CM3
C
C    VLIQ = VOLUMEN DEL LIQUIDO EN CM3
C
C    PSAT = PRESION DE VAPOR EN ATM
C	
C
C
C
C LA SENTENCIA 449 ES PARA REPETIR TODO EL CALCULO UNA VEZ QUE SE MODIFICA
C LA PRESION DE VAPOR 
C
C BLANQUEO
C
	IERRPVAP =0
C
	RUNIV = 82.05 !atm cm3/(K mol) 
C
C BUENA INICIALIZACION DE LA PSAT (ahora inicializo con la Pexp)
C
	ERRCOMP=0
C
c	CALL ROBUSTO4(NC,DC,RN,TEMPCRIT,TEMP,NG,NU,QAREA 
c    @,TSTR,GSTR,GDOT,GDDOT,RKIJ,RKTIJ,ALFAIJ,NGA,ONUASOC,MASSOC
c     @                 ,ENASS,RKASS,PSAT,RLAMBDA3,IERRROB)
C
			ierrrob=0
c			IF(IERRROB.NE.0) GO TO 419
C

 449 	CONTINUE
C
C
C INICIALIZACION VOLUMEN DEL VAPOR
C
	CALL VAPINICI(NC,DC,RN,TEMPCRIT,TEMP,NG,NU,QAREA 
     @,TSTR,GSTR,GDOT,GDDOT,RKIJ,RKTIJ,ALFAIJ,NGA,ONUASOC,MASSOC
     @,ENASS,RKASS,PSAT,VVAP,FFIFV,IERRVAP)   
C
	VOLVAP = VVAP       !almaceno valores por si falla la
	FUGVAP = FFIFV(1)   !                    compatibilizacion
C
   	IF(IERRVAP.NE.0) GO TO 419
C
	IF(ERRCOMP.NE.0) GO TO 132
C
C COMPATIBILIZACION DEL VOLUMEN DEL VAPOR CON LA PSAT
C
	CALL COMPATVVAP(NC,DC,RN,TEMPCRIT,TEMP,NG,NU,QAREA 
     @,TSTR,GSTR,GDOT,GDDOT,RKIJ,RKTIJ,ALFAIJ,NGA,ONUASOC,MASSOC
     @,ENASS,RKASS,PSAT,VVAP,FFIFV,IERRVC) 
C
   	IF(IERRVC.NE.0) THEN !recupero valores de la inicializacion
		VVAP = VOLVAP 
		FFIFV(1) = FUGVAP 
		IERRVC = 0
	  ELSE
	   CONTINUE
	END IF
C
C INICIALIZACION DEL VOLUMEN DEL LIQUIDO
C
 132	CALL LIQINICI(NC,DC,RN,TEMPCRIT,TEMP,NG,NU,QAREA 
     @,TSTR,GSTR,GDOT,GDDOT,RKIJ,RKTIJ,ALFAIJ,NGA,ONUASOC,MASSOC
     @,ENASS,RKASS,RLAMBDA3,PSAT,VLIQ,FFIFL,IERRLI)
C
	VOLLIQ = VLIQ       !almaceno valores por si falla la
	FUGLIQ = FFIFL(1)   !                    compatibilizacion
C
   	IF(IERRLI.NE.0) GO TO 419
C
C COMPATIBILIZACION DEL VOL. LIQ. CON LA PRESION DE SATURACION
C
C
	IF(ERRCOMP.NE.0) GO TO 135
C
	CALL COMPATVLIQ(NC,DC,RN,TEMPCRIT,TEMP,NG,NU,QAREA 
     @,TSTR,GSTR,GDOT,GDDOT,RKIJ,RKTIJ,ALFAIJ,NGA,ONUASOC,MASSOC
     @,ENASS,RKASS,RLAMBDA3,PSAT,VLIQ,FFIFL,IERRLC)
C
   	IF(IERRLC.NE.0) THEN
C
	     VLIQ = VOLLIQ 
	     FFIFL(1) = FUGLIQ  
	     IERRLC = 0
C
	  ELSE
	   CONTINUE
	END IF
C
 	IF(DABS((VLIQ-VVAP)/VVAP).LT.1.D-3) THEN
		   ERRCOMP = 1
		   GO TO 449
				ELSE
		   ERRCOMP = 0
	END IF
C 
C SI LOS COEFICIENTES DE FUGACIDAD NO SON IGUALES CORRIJO PSAT
C
 135	IF(ERRCOMP.EQ.1) ERRCOMP=0
C
C RECALCULO DE PSAT 
C
C (SUSTITUCION DIRECTA ERA:  
C
 	ZFASL = PSAT * VLIQ / RUNIV / TEMP  
	ZFASV = PSAT * VVAP / RUNIV / TEMP
C	write(*,*)ZFASL,ZFASV,FFIFL(1),FFIFV(1)
C
	BLOCKU = (1. -  DLOG(FFIFL(1)/FFIFV(1))/(ZFASL-ZFASV))       
C
	IF(BLOCKU.GT.0) THEN
C				 Newton
				PSAT1 = PSAT*BLOCKU  
	 ELSE
C				 Sust. Directa
			        PSAT1 = PSAT*FFIFL(1)/FFIFV(1)	      
	END IF	
C
C
C SE TOLERA UN ERROR DE 0.01 %
C
	IF(DABS((PSAT1-PSAT)/PSAT).LT.1.D-4) THEN 
		GO TO 448
	      ELSE
	        PSAT=PSAT1
C		WRITE(6,*) ' PSAT actual = ', PSAT
		GO TO 449
	END IF
C
C CALCULO DE FACTORES DE COMPRESIBILIDAD
C
 448	CONTINUE
C
C
 419	IF(IERRVAP.NE.0.OR.IERRVC.NE.0.OR.
     @IERRLC.NE.0.OR.IERRLI.NE.0.OR.IERRROB.NE.0) IERRPVAP =1
 	END  !FIN PVAP
