	SUBROUTINE ROBUSTO4(NC,DC,RN,TEMPCRIT,TEMP,NG,NU,QAREA 
     @,TSTR,GSTR,GDOT,GDDOT,RKIJ,RKTIJ,ALFAIJ,NGA,ONUASOC,MASSOC
     @                 ,ENASS,RKASS,PSAT,RLAMBDA3,IERRROB)
C
C BUSQUEDA DE CEROS DE LA DERIVADA PRIMERA DE LA PRESION CON RESPECTO AL 
C   VOL, O DE PUNTOS EN QUE ESA DERIVADA PRIMERA ES POSITIVA
C
	IMPLICIT REAL*8 (A-H,O-Z)
C
	DIMENSION DC(1), RN(1)
	DIMENSION  TEMPCRIT(1)
	DIMENSION NU(10,1), QAREA(10), TSTR(10), GSTR(10) 
	DIMENSION GDOT(10), GDDOT(10), RKIJ(10,10), RKTIJ(10,10)
	DIMENSION ALFAIJ(10,10) 
        DIMENSION MASSOC(12),ENASS(6,12,6,12), RKASS(6,12,6,12)
        DIMENSION ONUASOC(12,1)
C
	DIMENSION FFIFL(1)
C
	DIMENSION DERSEG(3),VDERSEG(3)   !arreglo para guardar algunos 
C					valores de la 
C					derivada segunda, y de los vol
C					correspondientes
C
C	WRITE(6,*) 'COMIENZA METODO ROBUSTO'
C
	NONGA=0
C
	IERRROB = 0
C
	RUNIV = 82.05 !atm cm3/(K mol) 
C
	VOLFIRST = 2 * RLAMBDA3 * 3.15 / 6 !2 VECES EL COVOLUMEN
	VOLLAST = RUNIV*TEMP/(0.05)
C
C el volumen inicial del gas  se toma a una presion de 0.05 atm
C  para asegurar un volumen suficientemente grande
C
C
	NCONT = 0
C
 	VOL1 = VOLFIRST 
	VOL3 = VOL1 + 1.D-5*VOL1
 170	VOL1 = VOL3 / (1 + 1.D-5)
	VOL5 = VOL1 + 2.D-5*VOL1
C
	VOL2 = (VOL1 + VOL3 )/2
	VOL4 = (VOL3 + VOL5 )/2
C
C VOL2 = (VOL1 + VOL3 )/2
C
C VOL4 = (VOL3 + VOL5 )/2
C
	NCOD=1
        CALL ASSOCGCEOS(NCOD,NC,DC,RN,TEMPCRIT,VOL1,TEMP,NG,NU,QAREA
     @,TSTR,GSTR,GDOT,GDDOT,RKIJ,RKTIJ,ALFAIJ,NGA,ONUASOC,MASSOC
     @,ENASS,RKASS,ARESTOT,ZFSL,FFIFL,IERRFUG,IERRZSIS,IERRREP,ierrasoc)
C
C
	PRESS1 = ZFSL * RUNIV * TEMP / VOL1
C
C   
	NCOD=1
        CALL ASSOCGCEOS(NCOD,NC,DC,RN,TEMPCRIT,VOL3,TEMP,NG,NU,QAREA
     @,TSTR,GSTR,GDOT,GDDOT,RKIJ,RKTIJ,ALFAIJ,NGA,ONUASOC,MASSOC
     @,ENASS,RKASS,ARESTOT,ZFSL,FFIFL,IERRFUG,IERRZSIS,IERRREP,ierrasoc)
C
C
C
	PRESS3 = ZFSL * RUNIV * TEMP / VOL3
C   
	NCOD=1
 	CALL ASSOCGCEOS(NCOD,NC,DC,RN,TEMPCRIT,VOL5,TEMP,NG,NU,QAREA 
     @,TSTR,GSTR,GDOT,GDDOT,RKIJ,RKTIJ,ALFAIJ,NGA,ONUASOC,MASSOC
     @,ENASS,RKASS,ARESTOT,ZFSL,FFIFL,IERRFUG,IERRZSIS,IERRREP,ierrasoc)
C
C
C
	PRESS5 = ZFSL * RUNIV * TEMP / VOL5
C
C ESTIMACION DE LA DERIVADA PRIMERA EN VOL2 Y VOL4
C
	DERI2 = (PRESS3 - PRESS1)/ (VOL3 - VOL1)
C
	DERI4 = (PRESS5 - PRESS3)/ (VOL5 - VOL3)
C
C ESTIMACION DE LA DERIVADA PRIMERA EN VOL3
C
	DERI3 = (PRESS5 - PRESS1)/ (VOL5 - VOL1)
C
C ESTIMACION DE LA DERIVADA SEGUNDA EN VOL3
C
	SEGDERI3 = (DERI4-DERI2)/(VOL4-VOL2)
C
C
	IF(NCONT.EQ.1) THEN
C-------------------------------------------------------------
C METODO DE LA SECANTE PARA HALLAR EL CERO DE VOLUMEN MAYOR DE LA
C  PRIMERA DERIVADA
C
C ESTABLECIMIENTO DE LIMITES
C
	IF((VSECMIN*VSECMAX).EQ.0) THEN
			IF(DERI3.GT.0) THEN
				 VSECMIN = VOL3
				 SECPOS = DERI3  
				 IF(VSECMAX.NE.0) GO TO 768
				 PASO = 2*PASO
				 VOL3 = VSECMIN + PASO
				 NSEC = NSEC + 1 
				 GO TO 170
			       ELSE
				 VSECMAX = VOL3
				 SECNEG = DERI3  
				 IF(VSECMIN.NE.0) GO TO 768
				 PASO = PASO/2.
				 VOL3 = VSECMAX - PASO
				 NSEC = NSEC + 1
				 GO TO 170
		 	END IF
	ELSE
	 CONTINUE
	END IF
C
C ASIGNACION DE VALORES SEGUN SIGNO
C
	IF(DERI3.GT.0) THEN 
			 VSECMIN = VOL3
			 SECPOS = DERI3
		       ELSE
			 VSECMAX = VOL3
			 SECNEG = DERI3
	END IF
C
	IF(DABS(VSECMIN-VSECMAX).LT.1.D-4) GO TO 731
C	
C ESTIMACION DE UN NUEVO VOLUMEN
C         ALTERNO SECANTE CON BISECCION
C
	IF(NONGA.GT.10.AND.SEGDERI3.LT.0) GO TO 731 
C
 768	IF(NINGA.EQ.0) THEN
		RNEWVOL = VSECMIN - SECPOS * (VSECMAX - VSECMIN)/
     @ (SECNEG-SECPOS)
		NINGA=1
		NONGA = NONGA + 1
	 ELSE
		RNEWVOL = (VSECMAX + VSECMIN)/2.
		NINGA=0
		NONGA = NONGA + 1
	END IF
C
	VOL3 = RNEWVOL
	GO TO 170
C-------------------------------------------------------------
	ELSE
		CONTINUE
	END IF	
C
C ESTIMACION DE UNA RAIZ DE LA DERIV. 1A DE LA PRESION C/RESP AL VOL
C  POR METODO DE NEWTON
C
 731	RNEWVOL = VOL3 - DERI3/SEGDERI3 	
	IF(RNEWVOL.GT.VOLLAST) WRITE(6,*) 'PROBABLEMENTE SUPERCRITICO ' 
	IF(RNEWVOL.GT.VOLLAST) IERRROB = 1
	IF(RNEWVOL.GT.VOLLAST) GO TO 991
C
C TEST DE CONVERGENCIA
C
	IF(DABS(RNEWVOL-VOL3).LT.1.D-4.OR.DABS(DERI3).LT.1.D-8) THEN
			IF(NCONT.EQ.0) THEN 
				VMIN = VOL3
				PMIN = PRESS3
				NCONT = 1
				PASO = 0.1*VMIN
C						
				VOL3 = VMIN + PASO
				NSEC=0
				VSECMIN = 0
				VSECMAX = 0
				RNEWVOL = 0
				GO TO 170
			ELSE
				VMAX = VOL3
				PMAX = PRESS3
			END IF
		ELSE
			VOL3 = RNEWVOL
		 	GO TO 170
	END IF
C
	IF(PMIN.LT.0) PMIN = 0
	PSAT = (PMIN + PMAX)/2
C
C
C991	WRITE(6,*) 'TERMINA METODO ROBUSTO'
 991    CONTINUE
C
	END !FIN ROBUSTO4
