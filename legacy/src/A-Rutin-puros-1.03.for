C
	  VLIQ=0.5*(VLIQ + VLIQ2)
	  GO TO 446
	  
	ELSE
C
	  NITLC = NITLC + 1
	  IF(NITLC.GT.100) IERRLC = 1
	  
	  IF(NITLC.GT.100) GO TO 446
	  
	  GO TO 447
	  
	END IF
C
 446	IF(IERRFUG.EQ.1.OR.IERRZSIS.EQ.1.OR.IERRREP.EQ.1) IERRLC = 1
C
	IF(IERRLC.EQ.0) THEN
C
C	Calculo del coeficiente de fugacidad
C
C	ZFSL, VLIQ y FFIFL estan bien
	NCOD=2
        CALL ASSOCGCEOS(NCOD,NC,DC,RN,TEMPCRIT,VLIQ,TEMP,NG,NU,QAREA
     @,TSTR,GSTR,GDOT,GDDOT,RKIJ,RKTIJ,ALFAIJ,NGA,ONUASOC,MASSOC
     @,ENASS,RKASS,ARESTOT,ZFSL,FFIFL,IERRFUG,IERRZSIS,IERRREP,
     @ierrassoc)
	IF(IERRFUG.OR.IERRZSIS.OR.IERRREP.OR.ierrassoc.EQ.1)  IERRLC = 1
C
	 ELSE
	  CONTINUE
	END IF
C
	END !FIN COMPATVLIQ 
