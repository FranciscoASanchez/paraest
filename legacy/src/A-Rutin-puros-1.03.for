	SUBROUTINE LIQINICI(NC,DC,RN,TEMPCRIT,TEMP,NG,NU,QAREA 
     @,TSTR,GSTR,GDOT,GDDOT,RKIJ,RKTIJ,ALFAIJ,NGA,ONUASOC,MASSOC
     @,ENASS,RKASS,RLAMBDA3,PSAT,VLIQ,FFIFL,IERRLI)
C
C VLIQ = VALOR INICIAL DEL VOLUMEN DEL LIQUIDO
C
C
	IMPLICIT REAL*8 (A-H,O-Z)
C
	integer, parameter :: NGM = 10
	
	DIMENSION DC(1), RN(1)
	DIMENSION  TEMPCRIT(1)
	DIMENSION NU(NGM,1), QAREA(NGM), TSTR(NGM), GSTR(NGM) 
	DIMENSION GDOT(NGM), GDDOT(NGM), RKIJ(NGM,NGM), RKTIJ(NGM,NGM)
	DIMENSION ALFAIJ(NGM,NGM) 
	DIMENSION MASSOC(12),ENASS(6,12,6,12), RKASS(6,12,6,12)
	DIMENSION ONUASOC(12,1)
C
C
	DIMENSION FFIFL(1)
C
C BLANQUEO DE ALGUNAS VARIABLES LOCALES
C
	IERRFUG=0.
	IERRLI =0.
	IERRREP=0.
	IERRZSIS =0. 
	PRESS = 0. 
	PRESS0 =0.    
	PRESS1 =0.     
	VLIQ =  0.    
	VLIQ0 = 0.     
	VLIQ1 = 0.        
	ZFSL  = 0.         
	ZFSL0 = 0.          
	ZFSL1 = 0.        
	FFIFL(1)=0.                   
C
	RUNIV = 82.05 !atm cm3/(K mol) 
C
C INICIALIZACION DEL VOLUMEN DEL LIQUIDO (cm3 / mol)
C
	VLIQ = RLAMBDA3 * 3.141592 / 6.   !APROX COVOLUMEN
C
C    ES COVOLUMEN ^ MOLAR PORQUE EN LA SUBRUTINA CORRECCION LE IMPONGO
C     QUE HAYA SOLO UN  COMPONENTE Y QUE RN(1)=1.
C
C     inicializando extrictamente con el covolumen el termino de esf rig.
C                         					diverge
C
	CONST=1.8
C
 719	VLIQ0 = CONST * VLIQ !CONST veces el covolumen
C
	NCOD=1
      CALL ASSOCGCEOS(NCOD,NC,DC,RN,TEMPCRIT,VLIQ0,TEMP,NG,NU,QAREA,
     @                TSTR,GSTR,GDOT,GDDOT,RKIJ,RKTIJ,ALFAIJ,NGA,
     @                ONUASOC,MASSOC,ENASS,RKASS,ARESTOT,ZFSL0,FFIFL,
     @                IERRFUG,IERRZSIS,IERRREP,ierrassoc)
 

	IF(IERRFUG.OR.IERRZSIS.OR.IERRREP.OR.ierrassoc.EQ.1) GO TO 919
C
C
 	VLIQ1 = CONST * 1.0001 * VLIQ 	   
C
	NCOD=1
      CALL ASSOCGCEOS(NCOD,NC,DC,RN,TEMPCRIT,VLIQ1,TEMP,NG,NU,QAREA,
     @                TSTR,GSTR,GDOT,GDDOT,RKIJ,RKTIJ,ALFAIJ,NGA,
     @                ONUASOC,MASSOC,ENASS,RKASS,ARESTOT,ZFSL1,FFIFL,
     @                IERRFUG,IERRZSIS,IERRREP,ierrassoc)

C
	IF(IERRFUG.OR.IERRZSIS.OR.IERRREP.OR.ierrassoc.EQ.1)  GO TO 919
C
	PRESS0 = ZFSL0 * RUNIV * TEMP / VLIQ0
	PRESS1 = ZFSL1 * RUNIV * TEMP / VLIQ1
C
C EVITA PRESIONES MENORES QUE LA DE SATURACION (INCLUYENDO LAS NEGATIVAS)
C   EL FACTOR 1.4 TIENE QUE VER CON LA RELACION 
C
C         A = VOL DE ESFERAS/VOL MINIMO QUE PUEDEN OCUPAR LAS ESFERAS
C
C	  A = 0.74048             1/A = 1.35047
C
	IF(PRESS0.LT.PSAT.OR.PRESS1.LT.PSAT.AND.CONST.GT.1.4)THEN
		
921	  CONST = CONST - 6. D-03
	  GO TO 719
	
	END IF
C
C  CON LA ECUACION DE UNA RECTA PASANTE
C
C   POR (VLIQ0,PRESS0) Y (VLIQ1,PRESS1) CALCULO UNA APROXIMACION
C
C     AL VOLUMEN LIQUIDO
C 
 757	IF(DABS((PRESS0-PRESS1)/PRESS0).LT.1.D-10) GO TO 919
C
	VLIQ = (PSAT - PRESS1)*(VLIQ0-VLIQ1)/(PRESS0-PRESS1) + VLIQ1
C
C AHORA CALCULO LA PRESION DE VAPOR QUE REALMENTE CORRESPONDE AL VOLUMEN 
C OBTENIDO
C
	NCOD=1
      CALL ASSOCGCEOS(NCOD,NC,DC,RN,TEMPCRIT,VLIQ,TEMP,NG,NU,QAREA,
     @                TSTR,GSTR,GDOT,GDDOT,RKIJ,RKTIJ,ALFAIJ,NGA,
     @                ONUASOC,MASSOC,ENASS,RKASS,ARESTOT,ZFSL,FFIFL,
     @                IERRFUG,IERRZSIS,IERRREP,ierrassoc)

C
	IF(IERRFUG.OR.IERRZSIS.OR.IERRREP.OR.ierrassoc.EQ.1)  GO TO 919
C
	PRESS = ZFSL * RUNIV * TEMP / VLIQ
C
	IF(PRESS.GT.PSAT) THEN
	
	  VLIQ0=VLIQ1
	  VLIQ1=VLIQ
	  PRESS0=PRESS1
	  PRESS1=PRESS
	  GO TO 757
	
	ELSE
	
	  VLIQ=VLIQ1
	  PRESS=PRESS1

	END IF
C
919	IF(IERRFUG.EQ.1.OR.IERRZSIS.EQ.1.OR.IERRREP.EQ.1) IERRLI =1
C
	IF(IERRLI.EQ.0) THEN	
C
C    	CALCULO DEL COEF. DE FUGACIDAD
C
	  ZFSL3 = PRESS * VLIQ / (RUNIV * TEMP)
	  NCOD=2
!        CALL ASSOCGCEOS(NCOD,NC,DC,RN,TEMPCRIT,VLIQ,TEMP,NG,NU,QAREA
!     @,TSTR,GSTR,GDOT,GDDOT,RKIJ,RKTIJ,ALFAIJ,NGA,ONUASOC,MASSOC
!     @,ENASS,RKASS,ARESTOT,ZFSL3,FFIFL,IERRFUG,IERRZSIS,IERRREP,
!     @ierrassoc)
	  CALL ASSOCGCEOS(NCOD,NC,DC,RN,TEMPCRIT,VLIQ,TEMP,NG,NU,QAREA,
     @                  TSTR,GSTR,GDOT,GDDOT,RKIJ,RKTIJ,ALFAIJ,NGA,
     @                  ONUASOC,MASSOC,ENASS,RKASS,ARESTOT,ZFSL3,FFIFL,
     @                  IERRFUG,IERRZSIS,IERRREP,ierrassoc)


	  IF(IERRFUG.OR.IERRZSIS.OR.IERRREP.OR.ierrassoc.EQ.1)  IERRLI =1
C
!	 ELSE
!	  CONTINUE
	END IF
C
	END !FIN LIQINICI 
