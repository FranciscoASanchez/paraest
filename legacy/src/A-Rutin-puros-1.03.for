	SUBROUTINE COMPATVLIQ(NC,DC,RN,TEMPCRIT,TEMP,NG,NU,QAREA 
     @,TSTR,GSTR,GDOT,GDDOT,RKIJ,RKTIJ,ALFAIJ,NGA,ONUASOC,MASSOC
     @,ENASS,RKASS,RLAMBDA3,PSAT,VLIQ,FFIFL,IERRLC)
