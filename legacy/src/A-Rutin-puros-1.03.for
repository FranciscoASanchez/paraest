	SUBROUTINE COMPATVVAP(NC,DC,RN,TEMPCRIT,TEMP,NG,NU,QAREA 
     @,TSTR,GSTR,GDOT,GDDOT,RKIJ,RKTIJ,ALFAIJ,NGA,ONUASOC,MASSOC
     @,ENASS,RKASS,PSAT,VVAP,FFIFV,IERRVC) 
C
	IMPLICIT REAL*8 (A-H,O-Z)
C
	integer, parameter :: NGM = 10
	
	DIMENSION DC(1), RN(1)
	DIMENSION  TEMPCRIT(1)
	DIMENSION NU(NGM,1), QAREA(NGM), TSTR(NGM), GSTR(NGM) 
	DIMENSION GDOT(NGM), GDDOT(NGM), RKIJ(NGM,NGM), RKTIJ(NGM,NGM)
	DIMENSION ALFAIJ(NGM,NGM) 
        DIMENSION MASSOC(12),ENASS(6,12,6,12), RKASS(6,12,6,12)
        DIMENSION ONUASOC(12,1)
C
C
	DIMENSION FFIFV(1) 
C
C VVAP= VOL FASE VAPOR INICIAL (ANTES DE CORRER LA SUBRUTINA)
C     = VOL FASE VAPOR CONFORMADO CON LA PSAT (DESPUES DE CORRER LA SUB)
C
C
	IERRVC=0 
C
	RUNIV = 82.05 !atm cm3/(K mol) 
C
	NITCV = 0
C
C
C
 777	NCOD=1
	CALL ASSOCGCEOS(NCOD,NC,DC,RN,TEMPCRIT,VVAP,TEMP,NG,NU,QAREA
     @,TSTR,GSTR,GDOT,GDDOT,RKIJ,RKTIJ,ALFAIJ,NGA,ONUASOC,MASSOC
     @,ENASS,RKASS,ARESTOT,ZFSV,FFIFV,IERRFUG,IERRZSIS,IERRREP,
     @ierrassoc)


	IF(IERRFUG.OR.IERRZSIS.OR.IERRREP.OR.ierrassoc.EQ.1)  GO TO 787 
C
	VVAP2= ZFSV*RUNIV*TEMP/PSAT
C
	  IF(DABS((VVAP2-VVAP)/VVAP).LT.1.D-6) THEN
	    VVAP= 0.5*(VVAP + VVAP2)
	    
	    GO TO 787
	    
	  ELSE
	    VVAP=VVAP2
	    NITCV = NITCV + 1
	    IF(NITCV.GT.100) IERRVC = 1
	    
	    IF(NITCV.GT.100) GO TO 787
	    
	    GO TO 777
	    
	  END IF
C
 787 	IF(IERRFUG.EQ.1.OR.IERRZSIS.EQ.1.OR.IERRREP.EQ.1) IERRVC = 1
C
	IF(IERRVC.EQ.0) THEN 
C
C	Calculo del coeficiente de fugacidad
C
C       ZFSV esta bien, VVAP esta bien y FFIFV esta bien
	NCOD=2
	CALL ASSOCGCEOS(NCOD,NC,DC,RN,TEMPCRIT,VVAP,TEMP,NG,NU,QAREA
     @,TSTR,GSTR,GDOT,GDDOT,RKIJ,RKTIJ,ALFAIJ,NGA,ONUASOC,MASSOC
     @,ENASS,RKASS,ARESTOT,ZFSV,FFIFV,IERRFUG,IERRZSIS,IERRREP,
     @ierrassoc)
	IF(IERRFUG.OR.IERRZSIS.OR.IERRREP.OR.ierrassoc.EQ.1) IERRVC = 1
C
	 ELSE
	  CONTINUE
	END IF
C
	END !FIN COMPATVVAP 
