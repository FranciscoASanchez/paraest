	SUBROUTINE VAPINICI(NC,DC,RN,TEMPCRIT,TEMP,NG,NU,QAREA 
     @,TSTR,GSTR,GDOT,GDDOT,RKIJ,RKTIJ,ALFAIJ,NGA,ONUASOC,MASSOC
     @,ENASS,RKASS,PSAT,VVAP,FFIFV,IERRVAP)   
C
C VVAP = VALOR INICIAL DEL VOLUMEN DE LA FASE VAPOR
C
	IMPLICIT REAL*8 (A-H,O-Z)
	integer, parameter :: NGM = 10
C
	DIMENSION DC(1), RN(1)
	DIMENSION  TEMPCRIT(1)
	DIMENSION NU(NGM,1), QAREA(NGM), TSTR(NGM), GSTR(NGM) 
	DIMENSION GDOT(NGM), GDDOT(NGM), RKIJ(NGM,NGM), RKTIJ(NGM,NGM)
	DIMENSION ALFAIJ(NGM,NGM) 
	DIMENSION MASSOC(12),ENASS(6,12,6,12), RKASS(6,12,6,12)
	DIMENSION ONUASOC(12,1)
C
C
	DIMENSION FFIFV(1)
C
	IERRVAP=0   
C
	RUNIV = 82.05 !atm cm3/(K mol) 
C
C INICIALIZACION DEL VOLUMEN DEL VAPOR 
C
	VVAP0 = 2. * RUNIV * TEMP / PSAT  !VOLUMEN MOLAR gas ideal mult * 2 
C
	NCOD=1
      CALL ASSOCGCEOS(NCOD,NC,DC,RN,TEMPCRIT,VVAP0,TEMP,NG,NU,QAREA
     @,TSTR,GSTR,GDOT,GDDOT,RKIJ,RKTIJ,ALFAIJ,NGA,ONUASOC,MASSOC
     @,ENASS,RKASS,ARESTOT,ZFSV0,FFIFV,IERRFUG,IERRZSIS,IERRREP,
     @ierrassoc)
C
	IF(IERRFUG.OR.IERRZSIS.OR.IERRREP.OR.ierrassoc.EQ.1) GO TO 456
C
	PRESSV0 = ZFSV0 * RUNIV * TEMP / VVAP0
C
	VVAP1 = VVAP0/2. !volumen molar gas ideal
C
	NCOD=1
	CALL ASSOCGCEOS(NCOD,NC,DC,RN,TEMPCRIT,VVAP1,TEMP,NG,NU,QAREA
     @,TSTR,GSTR,GDOT,GDDOT,RKIJ,RKTIJ,ALFAIJ,NGA,ONUASOC,MASSOC
     @,ENASS,RKASS,ARESTOT,ZFSV1,FFIFV,IERRFUG,IERRZSIS,IERRREP,
     @ierrassoc)
C
	IF(IERRFUG.OR.IERRZSIS.OR.IERRREP.OR.ierrassoc.EQ.1) GO TO 456
C
	PRESSV1 = ZFSV1 * RUNIV * TEMP / VVAP1
C
C  CON LA ECUACION DE UNA HIPERBOLA PASANTE
C
C   POR (VVAP0,PRESSV0) Y (VVAP1,PRESSV1) CALCULO UNA APROXIMACION
C
C   AL VOLUMEN DEL VAPOR
C 
 131	IF(DABS((PRESSV0-PRESSV1)/PRESSV0).LT.1.D-10) GO TO 456
	IF(DABS((VVAP0-VVAP1)/VVAP0).LT.1.D-10) GO TO 456
C
	VVAP = VVAP0*VVAP1*(PRESSV0-PRESSV1)
	VVAP = VVAP/(PSAT*VVAP1 - PSAT*VVAP0 + PRESSV0*VVAP0 - PRESSV1*VVA
     *P1)  
C
C AHORA CALCULO LA VERDADERA PRESION QUE CORRESPONDE AL VOLUMEN CALCULADO
C
C
	NCOD=1
        CALL ASSOCGCEOS(NCOD,NC,DC,RN,TEMPCRIT,VVAP,TEMP,NG,NU,QAREA
     @,TSTR,GSTR,GDOT,GDDOT,RKIJ,RKTIJ,ALFAIJ,NGA,ONUASOC,MASSOC
     @,ENASS,RKASS,ARESTOT,ZFSV,FFIFV,IERRFUG,IERRZSIS,IERRREP,
     @ierrassoc)
C
	IF(IERRFUG.OR.IERRZSIS.OR.IERRREP.OR.ierrassoc.EQ.1) GO TO 456
C
	PRESSV = ZFSV * RUNIV * TEMP / VVAP
C
	IF(PRESSV.LT.PSAT) THEN
C
	  VVAP0=VVAP1
	  VVAP1=VVAP
	  PRESSV0=PRESSV1
	  PRESSV1=PRESSV
	  GO TO 131
	  
	ELSE
C
	  VVAP=VVAP1
	  PRESSV=PRESSV1
	  
	END IF
C
 456	IF(IERRFUG.OR.IERRZSIS.OR.IERRREP.OR.ierrassoc.EQ.1)  IERRVAP=1 	
C
	IF(IERRVAP.EQ.0) THEN 	
C
C 	CALCULO DEL COEFICIENTE DE FUGACIDAD
C
	ZFSV3=  PRESSV * VVAP / (RUNIV * TEMP) 
	NCOD=2
      CALL ASSOCGCEOS(NCOD,NC,DC,RN,TEMPCRIT,VVAP,TEMP,NG,NU,QAREA
     @,TSTR,GSTR,GDOT,GDDOT,RKIJ,RKTIJ,ALFAIJ,NGA,ONUASOC,MASSOC
     @,ENASS,RKASS,ARESTOT,ZFSV3,FFIFV,IERRFUG,IERRZSIS,IERRREP,
     @ierrassoc)

	IF(IERRFUG.OR.IERRZSIS.OR.IERRREP.OR.ierrassoc.EQ.1)  IERRVAP=1 	
C
	 ELSE
	  CONTINUE
	END IF
C
	ENDSUBROUTINE VAPINICI
