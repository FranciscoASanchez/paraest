	SUBROUTINE SOFT2(NC,DC,TEMPCRIT,TEMP,D)
C
C CAlCULA LOS DIAMETROS DE ESFERAS RIGIDAS A LA TEMP DEL SISTEMA
C
	Implicit real*8 (A-H, O-Z)
	DIMENSION DC(1), TEMPCRIT(1), D(1)
C
C CALCULO DE LOS D(I)
C
	DO I=1,NC
	  HELPDC=DEXP(-2*TEMPCRIT(I)/3./TEMP)
	  D(I)=1.065655*DC(I)*(1-0.12*HELPDC)
	END DO
C
	ENDSUBROUTINE SOFT2
